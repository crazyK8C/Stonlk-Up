import type { ContentQuestion } from '../shared/types.js';
import { z } from 'zod';
export const contentSchema = z
  .object({
    id: z.string(),
    title: z.string(),
    description: z.string(),
    category: z.string(),
    difficulty: z.enum(['Beginner', 'Intermediate', 'Advanced', 'Quant']),
    format: z.enum([
      'prediction',
      'multiple-choice',
      'numerical',
      'probability',
      'portfolio',
      'chart',
      'strategy',
    ]),
    options: z.array(z.object({ id: z.string(), label: z.string(), icon: z.string() })).min(2),
    correctAnswer: z.string(),
    explanation: z.string(),
    takeaway: z.string(),
    concept: z.string(),
    kind: z.enum(['historical', 'model']),
    date: z.string(),
    ticker: z.string(),
    source: z.object({ label: z.string(), url: z.string().url() }),
    reward: z.object({ xp: z.number().int().nonnegative(), coins: z.number().int().nonnegative() }),
    chart: z
      .object({ label: z.string(), values: z.array(z.number()).min(2), unit: z.string() })
      .optional(),
  })
  .refine(
    (q) => q.options.some((o) => o.id === q.correctAnswer),
    'Correct answer must reference an option',
  );
const investor = {
  label: 'Further reading · SEC investor education',
  url: 'https://www.sec.gov/files/investor/pubs/assetallocation.htm',
};
function q(
  id: string,
  title: string,
  description: string,
  labels: string[],
  answer: number,
  explanation: string,
  concept: string,
  extra: Partial<ContentQuestion> = {},
): ContentQuestion {
  return {
    id,
    title,
    description,
    options: labels.map((label, i) => ({
      id: String(i),
      label,
      icon: ['↗', '↘', '→', '?'][i % 4],
    })),
    correctAnswer: String(answer),
    explanation,
    takeaway: concept,
    concept,
    category: 'Market basics',
    difficulty: 'Beginner',
    format: 'prediction',
    kind: 'model',
    date: 'SIMULATED SCENARIO',
    ticker: 'MARKET',
    source: investor,
    reward: { xp: 100, coins: 15 },
    ...extra,
  };
}
